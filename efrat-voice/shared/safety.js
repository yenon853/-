// מילות מפתח שמסמנות מצוקה או סכנה ומחייבות הפניה למבוגר.
// הבדיקה רצה גם בדפדפן וגם בשרת, כדי שלא תלוי רק במודל השפה.
export const SAFETY_KEYWORDS = [
  'מרביצים לי',
  'הרביץ לי',
  'הרביצה לי',
  'מכים אותי',
  'היכה אותי',
  'בעט בי',
  'אלימות',
  'דם',
  'להכאיב לעצמי',
  'לפגוע בעצמי',
  'פוגע בעצמי',
  'פוגעת בעצמי',
  'לא רוצה לחיות',
  'רוצה למות',
  'להתאבד',
  'מאיים עליי',
  'מאיימים עליי',
  'מאיים עלי',
  'נגע לי',
  'נוגע בי',
  'סכין',
  'חרם'
];

export function containsSafetyRisk(text = '') {
  const t = String(text);
  return SAFETY_KEYWORDS.some((kw) => t.includes(kw));
}
